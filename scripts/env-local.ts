// Writes .env.local from the running local Supabase stack (`supabase status`).
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";

const force = process.argv.includes("--force");
if (existsSync(".env.local") && !force) {
  console.log(".env.local already exists. Re-run with --force to overwrite.");
  process.exit(0);
}

let raw: string;
try {
  raw = execFileSync("pnpm", ["exec", "supabase", "status", "-o", "env"], { encoding: "utf8" });
} catch {
  console.error("Could not read `supabase status`. Start the stack first: pnpm db:start");
  process.exit(1);
}

const status = Object.fromEntries(
  raw
    .split("\n")
    .map((line) => line.match(/^([A-Z_]+)="?(.*?)"?$/))
    .filter((m): m is RegExpMatchArray => m !== null)
    .map((m) => [m[1], m[2]]),
);

const required = ["API_URL", "PUBLISHABLE_KEY", "DB_URL"];
const missing = required.filter((k) => !status[k]);
if (missing.length) {
  console.error(`supabase status is missing ${missing.join(", ")}`);
  process.exit(1);
}

writeFileSync(
  ".env.local",
  [
    "# Generated by `pnpm env:local` from the local Supabase stack. Not committed.",
    `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}`,
    "NEXT_PUBLIC_SITE_URL=http://localhost:3000",
    `DATABASE_URL=${status.DB_URL}`,
    `MAILPIT_URL=${status.MAILPIT_URL ?? "http://127.0.0.1:54324"}`,
    "",
  ].join("\n"),
);
console.log("Wrote .env.local");
